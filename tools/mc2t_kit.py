#!/usr/bin/env python3
"""MC2T player-test kit generator.

Builds the facilitator materials for the human-participant parts of the
Mechanic Coherence & Clarity Test, with ground-truth answers computed from
the game's own data and rules (CardResolver: round half up of base x
(room affinity x question multiplier); guard, draw and gaffe never scale).
Usage: python3 tools/mc2t_kit.py --write design/review/MC2T_TEST_KIT_2026-11-06.md
"""
import json, os, sys, math
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def load(n):
    with open(os.path.join(ROOT, "data", n + ".json"), encoding="utf-8") as f: return json.load(f)
def half_up(x): return int(math.floor(x + 0.5))

cards = {c["card_id"]: c for c in load("cards")}
stages = {s["stage_id"]: s for s in load("stages")}
aff = {a["element"]: a["multipliers"] for a in load("affinity")}
bal = load("balance")
bal = {r["key"]: r["value"] for r in bal} if isinstance(bal, list) else bal
if isinstance(bal, dict) and "question_strong_multiplier" not in bal:
    bal = {k: (v.get("value") if isinstance(v, dict) else v) for k, v in bal.items()}
STRONG = float(bal.get("question_strong_multiplier", 1.3))
WEAK = float(bal.get("question_weak_multiplier", 0.7))

def card_result(cid, sid, q=1.0):
    c = cards[cid]; m = aff[c["suit"]].get(sid, 1.0) * q
    return {"gain": half_up((c["self_plus"] or 0) * m), "opp": half_up((c["opp_minus"] or 0) * m),
            "guard": c["guard"] or 0, "draw": c["draw"] or 0, "gaffe": c["gaffe"] or 0,
            "mult": m, "base_gain": c["self_plus"] or 0, "base_opp": c["opp_minus"] or 0}

def pick_stages(cid):
    """A stage where the card is boosted, one where it is suppressed (combat only)."""
    suit = cards[cid]["suit"]
    combat = [s for s in stages.values() if s["mode"] == "Combat" and s["stage_id"] in aff[suit]]
    hi = max(combat, key=lambda s: (aff[suit][s["stage_id"]], -int(s["stage_id"][2:])))
    lo = min(combat, key=lambda s: (aff[suit][s["stage_id"]], int(s["stage_id"][2:])))
    return hi, lo

def main():
    L = []; P = L.append
    P("# MC2T player-test kit\n")
    P("*Generated by `tools/mc2t_kit.py` from the game's data. Answers use the game's own rule: each support number is `round half up (base x room multiplier x question multiplier)`; guard, drawing and gaffes are never scaled.*\n")
    P("## 0. Quick reference\n")
    P("| Item | Value |\n|---|---|")
    P("| Participants | 5 per round, 3 rounds (RITE): fix top issues between rounds |")
    P("| Segments | New-to-genre, deckbuilder-literate, politics-literate (at least 1 each); phone in portrait, own thumb |")
    P("| Session | Cold start, 15 min think-aloud play, 3 freeze probes, 6 predict-then-reveal items, 8 term definitions, debrief |")
    P(f"| Question multipliers | strong {STRONG}, weak {WEAK} |")
    P("| Promised-answer rule | A card's printed numbers are base values; the room and the question change Gain and Opponent; Guard, Draw and Gaffe do not scale |\n")

    P("## 1. Predict-then-reveal items (criteria C2, K2)\n")
    P("Show the card face and the room's Details panel. Ask: *'If you play this now, what changes?'* Record each number the participant gives, then play it and compare. Score **1 = all numbers right, 0.5 = direction right but a number wrong, 0 = wrong direction or cannot say.**\n")
    items = ["C31", "C15", "C27"]
    n = 0
    for cid in items:
        c = cards[cid]; hi, lo = pick_stages(cid)
        P(f"### Card {cid} *{c['name_en']}* ({c['suit']}, cost {c['cost']}): printed `{c['effect_text']}`\n")
        P("| Item | Room | Question | Gain | Opponent | Guard | Draw | Gaffe |\n|---|---|---|---|---|---|---|---|")
        for label, s, q, qn in [("A", hi, 1.0, "none"), ("B", lo, 1.0, "none"), ("C", hi, STRONG, "invites this suit (strong)"), ("D", hi, WEAK, "poor answer (weak)")]:
            n += 1; r = card_result(cid, s["stage_id"], q)
            P(f"| P{n} ({label}) | {s['stage_id']} {s['name_en']} (x{aff[c['suit']][s['stage_id']]}) | {qn} | **{r['gain']}** | **{r['opp']}** | {r['guard']} | {r['draw']} | {r['gaffe']} |")
        P("")
    P("*Pass mark for criterion K2 (prediction accuracy): at least 80% of the 12 items scored 1 across the median participant. The protocol's critical gate is a median of 0.5 or more.*\n")

    P("## 2. SAGAT freeze probes (criterion C1)\n")
    P("Freeze the screen (cover it or pause), then ask. Ground truth comes from the engine state at the freeze; the facilitator reads it off the Details panel.\n")
    P("| # | When | Ask | Ground truth |\n|---|---|---|---|")
    P("| F1 | Turn 2 of the first battle | What will the opponent do next turn? | The intent line, if shown; 'unknown' only if the card that reveals it was not played |")
    P("| F2 | After a gaffe | How close are you to losing because of gaffes? | Gaffe meter value against the stage's gaffe limit (Details) |")
    P("| F3 | Mid-battle | What do you need to win, and how far away are you? | Support bar value against the threshold; turns left |")
    P("| F4 | After a card with Guard | What does Guard do and how much do you have? | Guard banks up to the cap (rules.json `guard_cap`); it absorbs the opponent's next attack |")
    P("| F5 | In the Office | What would happen if you start a 31-hour level with 2 hours left in the week? | The level cannot start (a level must end within the work week) |\n")

    P("## 3. Term definitions (criterion C4)\n")
    P("Ask: *'In your own words, what does ___ mean in this game?'* Score 1 correct, 0.5 partly, 0 wrong. Ground truth in the right column comes from `design/GAME_SYSTEMS.md`.\n")
    P("| Term | Meaning in this game |\n|---|---|")
    for t, m in [
        ("Threshold", "The support number you must reach to win the stage"),
        ("Gaffe meter", "Fills with mistakes; when full you lose the stage"),
        ("Guard", "A bank (cap 5) that blocks the opponent's next attack"),
        ("Standing", "How much one organization or party trusts you; unlocks backings, requests and votes"),
        ("Backing", "A perk an organization lends you for a stage or a level; gated by standing"),
        ("Constituency support", "One of four meta numbers; at 15 or below a Town Hall is forced"),
        ("Party support", "One of four meta numbers; at 0 funding freezes"),
        ("Legislative Work", "Bills you carried and the laws they became"),
    ]: P(f"| {t} | {m} |")
    P("")

    P("## 4. Coherence probes (criteria K1 to K5)\n")
    P("| # | Probe | Pass |\n|---|---|---|")
    for p in [
        ("K1", "Sort 12 UI words into 'same thing' groups (card sort); give the participant: Guard, Block, Gaffe, Standing, Support, Backing, Booster, Level, Stage, Room, Threshold, Member", "Participants group Backing with Booster; the designer decides whether they should (see report finding L1)"),
        ("K2", "Predict items P1 to P12 above", "Median 0.5 or more (gate), 80% target"),
        ("K3", "After a lost stage: 'Why did you lose?'", "Participant names the true cause (gaffe meter, turn limit, support at zero) from the result panel alone"),
        ("K4", "After a delayed consequence (a promise, a vote, decay): 'What caused this?'", "Participant traces it to their own earlier choice"),
        ("K5", "Teach-back: 'Explain to a friend how a turn works in 60 seconds'", "Mentions energy, hand, a question, the opponent's reply"),
    ]: P(f"| {p[0]} | {p[1]} | {p[2]} |")
    P("")

    P("## 5. Mobile probes (criteria MO1 to MO7)\n")
    P("| # | Task | Measure |\n|---|---|---|")
    for p in [
        ("MO1", "Play one battle one-handed (thumb) in portrait", "Count mis-taps (a tap that hits a neighbouring control); target under 3 percent of taps; gate over 10 percent"),
        ("MO2", "Read a card at arm's length", "Can the participant read the cost and numbers without zooming?"),
        ("MO5", "Lock the phone mid-stage for one minute, then return", "Is the stage still where they left it? (Known gap: nothing saves mid-stage; see report)"),
        ("MO6", "Rotate or switch to another app and back", "No lost state, no layout break"),
    ]: P(f"| {p[0]} | {p[1]} | {p[2]} |")
    P("")
    P("## 6. Recording sheet\n")
    P("| Participant | Segment | Device | Predict score (12) | Freeze probes (5) | Terms (8) | Mis-taps / taps | Notes |\n|---|---|---|---|---|---|---|---|\n| | | | | | | | |\n")
    out = "\n".join(L)
    if "--write" in sys.argv:
        p = sys.argv[sys.argv.index("--write") + 1]
        open(os.path.join(ROOT, p), "w", encoding="utf-8").write(out + "\n"); print("wrote", p)
    else: print(out)
main()
