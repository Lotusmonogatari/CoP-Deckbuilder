#!/usr/bin/env python3
"""Choice honesty audit (2026-10-31, Cameron): every set of player choices,
checked against the house rules for choices.

Usage:  python3 tools/choice_audit.py            # summary to the screen
        python3 tools/choice_audit.py --write    # also design/review/CHOICE_AUDIT.md

A set breaks the rules when a choice is outside 4-12 words, or the longest is
more than 1.75 times the shortest. Promise phrases ("I will", "I'll") are
counted so a set where only one choice commits to anything stands out. Reads
data/*.json only; never edits anything.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "data"
MIN_WORDS, MAX_WORDS, MAX_RATIO = 4, 12, 1.75
PROMISE = re.compile(r"\b(I will|I'll|I promise|I commit|I'm going to|I am going to)\b", re.I)


def load(name):
    with open(D / f"{name}.json", encoding="utf-8") as f:
        return json.load(f)


def words(text):
    return len(str(text or "").split())


def sets():
    out = []
    for q in load("visitor_questions"):
        out.append(("Visitor Questions", q["question_id"], q.get("question_text", ""),
                    [q.get("choice_" + c) or "" for c in "abcd"]))
    by_event = {}
    for c in load("event_choices"):
        text = str(c.get("choice_text") or "")
        if text.startswith("@") or text == "Decline":
            continue
        by_event.setdefault(c["event_id"], []).append(text)
    titles = {e["event_id"]: e.get("title", "") for e in load("events")}
    for eid, texts in by_event.items():
        out.append(("Event Choices", eid, titles.get(eid, ""), texts))
    return out


def problems(choices):
    counts = [words(c) for c in choices if c]
    found = []
    if not counts:
        return found, counts
    if min(counts) < MIN_WORDS:
        found.append(f"shorter than {MIN_WORDS} words")
    if max(counts) > MAX_WORDS:
        found.append(f"longer than {MAX_WORDS} words")
    if max(counts) > MAX_RATIO * max(1, min(counts)):
        found.append(f"longest is {max(counts) / max(1, min(counts)):.1f}x the shortest")
    return found, counts


def note(choices):
    """Not a rule break, a prompt for part B (commitments): only one choice
    promises an action."""
    promises = sum(1 for c in choices if PROMISE.search(c or ""))
    return "only one choice promises an action" if promises == 1 and len(choices) > 2 else ""


def main():
    rows = []
    for tab, ident, prompt, choices in sets():
        found, counts = problems(choices)
        ratio = max(counts) / max(1, min(counts)) if counts else 0
        rows.append((bool(found), ratio, tab, ident, prompt, choices, counts, found, note(choices)))
    flagged = [r for r in rows if r[0]]
    flagged.sort(key=lambda r: -r[1])
    lines = ["# Choice audit (generated by tools/choice_audit.py)", "",
             f"Rules: every choice {MIN_WORDS}-{MAX_WORDS} words; the longest at most {MAX_RATIO}x the shortest; "
             "each choice a sincere position; concrete steps matched across choices.", "",
             f"{len(flagged)} of {len(rows)} sets break a rule.", "",
             f"{sum(1 for r in rows if r[8])} sets have only one choice that promises an action (a note for the commitments work, not a rule break).", "",
             "| Tab | ID | Words | Problems | Note | Choices |", "|---|---|---|---|---|---|"]
    for _bad, _ratio, tab, ident, _prompt, choices, counts, found, promise_note in flagged:
        shown = " / ".join(c.replace("|", "/") for c in choices)
        lines.append(f"| {tab} | {ident} | {', '.join(map(str, counts))} | {'; '.join(found)} | {promise_note} | {shown} |")
    text = "\n".join(lines) + "\n"
    print(f"{len(flagged)} of {len(rows)} sets break a rule")
    if "--write" in sys.argv:
        (ROOT / "design" / "review" / "CHOICE_AUDIT.md").write_text(text, encoding="utf-8")
        print("wrote design/review/CHOICE_AUDIT.md")


if __name__ == "__main__":
    main()
