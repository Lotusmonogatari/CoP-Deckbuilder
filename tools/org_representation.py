"""How often each of the 32 organizations appears in events, event choices,
visitors and visitor questions (read-only; reads data/*.json, prints markdown).

An organization 'appears' where it is a TARGET of a structured effect: a reward,
a promise reward or penalty, a visitor's reward or penalty, a visitor question's
answer effects. That is how the game itself moves standing, so it is the fairest
measure of who the content is about. 'Named in text' is a second, looser signal
(the organization's name in an event's title, flavor or result text).

Usage: python3 tools/org_representation.py > design/review/ORG_REPRESENTATION.md
"""
import json, re, collections, statistics as st
D = 'data/'
def load(f): return json.load(open(D + f + '.json'))
boosters = load('boosters'); names = {b['booster_id']: b['name_en'] for b in boosters}
tier = {b['booster_id']: b['tier'] for b in boosters}
IDS = sorted(names)
BO = re.compile(r'BO\d+')
def targets(v):
    return set(BO.findall(json.dumps(v, ensure_ascii=False))) & set(IDS) if v not in (None, '', []) else set()

events = load('events'); choices = load('event_choices')
visitors = load('visitors'); vqs = load('visitor_questions')

ev_touch = collections.defaultdict(set)      # org -> event ids
ev_choice = collections.Counter()            # org -> number of choices touching it
ev_weight = collections.Counter()            # org -> summed Random event weight
weight_of = {e['event_id']: (float(e['weight']) if e.get('weight') not in (None, 'None') else 0.0) for e in events}
trigger_of = {e['event_id']: e['trigger'] for e in events}
for c in choices:
    t = targets([c.get(k) for k in ('rewards', 'promise_kept', 'promise_broken', 'commitment')])
    for o in t:
        ev_touch[o].add(c['event_id']); ev_choice[o] += 1
for o, es in ev_touch.items():
    ev_weight[o] = sum(weight_of.get(e, 0) for e in es if trigger_of.get(e) == 'Random')
named = collections.defaultdict(set)
for e in events:
    blob = ' '.join(str(e.get(k, '')) for k in ('title', 'flavor'))
    blob += ' ' + ' '.join(str(c.get('result_text', '')) + ' ' + str(c.get('choice_text', '')) for c in choices if c['event_id'] == e['event_id'])
    for o in IDS:
        if names[o].lower() in blob.lower(): named[o].add(e['event_id'])

vis_any = collections.defaultdict(set); vis_primary = collections.Counter()
for v in visitors:
    rew = v.get('reward') or []
    ts = targets([v.get('reward'), v.get('penalty')])
    for o in ts: vis_any[o].add(v['visitor_id'])
    first = BO.findall(json.dumps(rew))
    if first and first[0] in names: vis_primary[first[0]] += 1
vq_touch = collections.defaultdict(set)
for q in vqs:
    for k in ('effects_a', 'effects_b', 'effects_c', 'effects_d'):
        for o in targets(q.get(k)): vq_touch[o].add(q['question_id'])

rows = []
tot_ev = sum(len(ev_touch[o]) for o in IDS) or 1
tot_vis = sum(len(vis_any[o]) for o in IDS) or 1
tot_vq = sum(len(vq_touch[o]) for o in IDS) or 1
for o in IDS:
    s_ev, s_vis, s_vq = len(ev_touch[o]) / tot_ev, len(vis_any[o]) / tot_vis, len(vq_touch[o]) / tot_vq
    combined = (s_ev + s_vis + s_vq) / 3
    rows.append(dict(id=o, name=names[o], tier=tier[o], events=len(ev_touch[o]), choices=ev_choice[o],
        weight=ev_weight[o], named=len(named[o]), visitors=len(vis_any[o]), primary=vis_primary[o],
        vqs=len(vq_touch[o]), share=combined, index=combined * len(IDS)))
rows.sort(key=lambda r: r['index'])
def band(i):
    if i < 0.5: return 'Under (far)'
    if i < 0.8: return 'Under'
    if i <= 1.25: return 'Balanced'
    if i <= 2.0: return 'Over'
    return 'Over (far)'
print('# Organization representation in events and visitors\n')
print('Generated by `tools/org_representation.py` from `data/*.json`. %d organizations, %d events (%d choices), %d visitors, %d visitor questions.\n' % (len(IDS), len(events), len(choices), len(visitors), len(vqs)))
print('| Org | Name | Tier | Events | Choices | Random weight | Named in text | Visitors | Visitors (lead) | Visitor Qs | Share | Index | Band |')
print('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for r in rows:
    print('| %s | %s | %s | %d | %d | %g | %d | %d | %d | %d | %.1f%% | %.2f | %s |' % (r['id'], r['name'], r['tier'], r['events'], r['choices'], r['weight'], r['named'], r['visitors'], r['primary'], r['vqs'], 100 * r['share'], r['index'], band(r['index'])))
print('\nFair share is %.2f%% each (index 1.00). Share is the average of an organization\'s share of event touches, visitor touches and visitor-question touches.' % (100 / len(IDS)))
print('\n## By tier\n')
bt = collections.defaultdict(list)
for r in rows: bt[r['tier']].append(r)
print('| Tier | Orgs | Mean index | Total events | Total visitors | Total visitor Qs |')
print('|---|---|---|---|---|---|')
for t, rs in sorted(bt.items()):
    print('| %s | %d | %.2f | %d | %d | %d |' % (t, len(rs), st.mean(r['index'] for r in rs), sum(r['events'] for r in rs), sum(r['visitors'] for r in rs), sum(r['vqs'] for r in rs)))
