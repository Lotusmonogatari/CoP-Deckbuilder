#!/usr/bin/env python3
"""MC2T keyword audit (criterion K1: one idea, one name).

Reads every player-facing sentence (Text tab, card effect text, backings,
shop items, How to Play) and reports:
  1. forbidden or legacy terms (from design/INFORMATION_STANDARDS.md section 2)
  2. synonym families: how many different words name one idea
  3. overloaded words: one word used for several ideas ("support")
  4. card-text sentence templates (how many ways a card says the same thing)
Usage: python3 tools/mc2t_lexicon.py [--write out.md]
"""
import json, re, sys, collections, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def load(n):
    with open(os.path.join(ROOT, "data", n + ".json"), encoding="utf-8") as f:
        return json.load(f)

def corpus():
    """(source, id, text) for every player-facing line."""
    out = []
    for r in load("strings"):
        if r.get("english"): out.append(("Text", r["key"], str(r["english"])))
    for c in load("cards"):
        if c.get("effect_text"): out.append(("Card", c["card_id"], c["effect_text"]))
    for fn in ("modifiers", "shop", "how_to_play"):
        try: rows = load(fn)
        except Exception: continue
        if isinstance(rows, dict): rows = list(rows.values())
        for i, r in enumerate(rows if isinstance(rows, list) else []):
            if not isinstance(r, dict): continue
            for k, v in r.items():
                if isinstance(v, str) and len(v) > 12 and re.search(r"[a-z]{3}", v) and k not in ("id","art_id","image"):
                    if any(t in k.lower() for t in ("text","desc","effect","body","name","title","line","tip")):
                        out.append((fn, f"{r.get('id', i)}.{k}", v))
    return out

FORBIDDEN = {
  r"\bjiban\b|\bkanban\b|\bkaban\b": "Sanban terms must not show",
  r"\byen\b": "use Funds / 円",
  r"\bdonors?\b": "organization / backing",
  r"\bsentiment\b|\bmood\b": "standing / opinion terms are fixed",
  r"\bvote (yes|no)\b|\byea\b|\byes vote\b|\bno vote\b": "Aye / Nay",
  r"\bmodifiers?\b": "backing",
  r"\bstatute book\b": "Legislative Work",
  r"\btier\b": "Staff Rank (staff) / no tier on screen",
  r"\bcolou?r(s|ed)?\b(?<!color)": "American spelling",
  r"\b(favour|honour|labour|behaviour|neighbour|centre|programme|organis|recognis|licence|defence|judgement)\w*": "American spelling",
  r"\bturn limit\b|\bhidden clock\b|\btime_units\b": "hidden clock stays hidden",
}
FAMILIES = {
  "protection": ["guard", "block", "shield", "armor", "armour", "defend", "defense"],
  "mistakes": ["gaffe", "slip", "blunder", "misstep", "faux pas"],
  "relationship": ["standing", "favorability", "favourability", "opinion", "reputation with", "goodwill", "relationship"],
  "perk": ["backing", "booster", "buff", "bonus", "perk", "boost"],
  "unit of play": ["stage", "level", "room", "round", "battle", "encounter", "fight"],
  "people you convince": ["member", "colleague", "legislator", "lawmaker", "representative", "mp"],
  "score": ["support", "approval", "points", "score", "gain"],
  "limit": ["threshold", "target", "goal", "quota", "line"],
}
OVERLOADED = ["support", "standing", "opinion", "reputation", "party", "level", "room", "draw", "gain", "guard", "stance"]

def words(t): return re.findall(r"[A-Za-z']+", t.lower())

def template(t):
    t = re.sub(r"<[^>]+>", "<X>", t)
    t = re.sub(r"\d+%?", "N", t)
    t = re.sub(r"\b(Suit|Segment)\b", "<X>", t)
    return t

def main():
    c = corpus(); md = []
    P = md.append
    P("# MC2T K1: keyword and lexicon audit\n")
    P(f"Generated by `tools/mc2t_lexicon.py` over {len(c)} player-facing lines.\n")
    P("## 1. Forbidden or legacy terms\n")
    hits = collections.defaultdict(list)
    for src, i, t in c:
        for pat, why in FORBIDDEN.items():
            if re.search(pat, t, re.I): hits[(pat, why)].append((src, i, t))
    if not hits: P("None found.\n")
    for (pat, why), rows in hits.items():
        P(f"**{why}** (`{pat}`): {len(rows)} line(s)\n")
        for s, i, t in rows[:8]: P(f"- `{s}:{i}` {t[:110]}")
        P("")
    P("## 2. Synonym families (one idea, one name)\n")
    P("| Idea | Word | Lines |\n|---|---|---|")
    for fam, ws in FAMILIES.items():
        cnt = {w: sum(1 for _,_,t in c if re.search(r"\b" + w + r"\w*", t, re.I)) for w in ws}
        used = {w: n for w, n in cnt.items() if n}
        for w, n in sorted(used.items(), key=lambda x: -x[1]):
            P(f"| {fam} | {w} | {n} |")
    P("")
    P("## 3. Overloaded words (examples of different meanings)\n")
    P("| Word | Lines | Distinct phrases (top 6) |\n|---|---|---|")
    for w in OVERLOADED:
        ph = collections.Counter()
        n = 0
        for _,_,t in c:
            ws = words(t)
            for k, x in enumerate(ws):
                if x == w or x == w + "s":
                    n += 1
                    ph[" ".join(ws[max(0,k-1):k+2])] += 1
        P(f"| {w} | {n} | " + "; ".join(f"{p} ({q})" for p, q in ph.most_common(6)) + " |")
    P("")
    P("## 4. Card-text sentence templates\n")
    tm = collections.Counter()
    for s, i, t in c:
        if s != "Card": continue
        for sent in re.split(r"(?<=\.)\s+", t):
            if sent.strip(): tm[template(sent.strip())] += 1
    P(f"{len(tm)} templates over {sum(tm.values())} sentences.\n")
    P("| Template | Uses |\n|---|---|")
    for t, n in tm.most_common(): P(f"| {t} | {n} |")
    out = "\n".join(md)
    if "--write" in sys.argv:
        p = sys.argv[sys.argv.index("--write") + 1]
        open(os.path.join(ROOT, p) if not os.path.isabs(p) else p, "w", encoding="utf-8").write(out + "\n")
        print("wrote", p)
    else: print(out)

main()
