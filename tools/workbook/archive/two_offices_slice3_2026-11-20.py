if __name__ == "__main__":
    w = WB("design/Game_Workbook.xlsx")

    def add_header(sheet, title):
        rows = w.rows(sheet)
        header = rows[min(rows)]
        if title in header.values():
            raise SystemExit("already there: %s on %s" % (title, sheet))
        letter = n2col(max(col2n(c) for c in header) + 1)
        w.set_cell(sheet, min(rows), letter, title, style_from=1)
        return letter

    # Slice 1 added the Events column and tagged EV47; this fills the rest.
    header = w.rows("Events")[1]
    col = [letter for letter, title in header.items() if title == "Location"][0]
    for event_id, office in EVENTS.items():
        w.set_cell("Events", w.find_row("Events", event_id), col, office)
    col = add_header("Event Choices", "Location")
    rows = w.rows("Event Choices")
    done = 0
    for number, cells in rows.items():
        key = "%s.%s" % (cells.get("A"), cells.get("B"))
        if key in PROMISES:
            w.set_cell("Event Choices", number, col, PROMISES[key])
            done += 1
    col = add_header("Office Notices", "Location")
    for notice_id, office in NOTICES.items():
        w.set_cell("Office Notices", w.find_row("Office Notices", notice_id), col, office)
    col = add_header("Office Ticker", "Location")
    for ticker_id, office in TICKER.items():
        w.set_cell("Office Ticker", w.find_row("Office Ticker", ticker_id), col, office)
    col = add_header("Visitors", "Location")
    for visitor_id, office in VISITORS.items():
        w.set_cell("Visitors", w.find_row("Visitors", visitor_id), col, office)
    w.save()
    print("tagged %d events, %d promise choices, %d notices, %d ticker lines, %d visitors" % (
        len(EVENTS), done, len(NOTICES), len(TICKER), len(VISITORS)))
