#!/usr/bin/env python3
"""Read-only audit of event lead organizations (2026-11-21, Cameron's rule): a lead is an organization the event's OWN text names,
usually the one bringing the issue forward; an organization with only a passive plus or minus from a choice is not a lead.
Writes a short report of what needs a human look. Reads data/*.json only; changes nothing.

    python3 tools/audit_event_leads.py [out.md]
"""
import json, re, sys, collections

events = json.load(open("data/events.json"))
choices = json.load(open("data/event_choices.json"))
boosters = {b["booster_id"]: b["name_en"] for b in json.load(open("data/boosters.json"))}
by = collections.defaultdict(list)
for c in choices:
    by[c["event_id"]].append(c)


def named(text):
    return [i for i, n in boosters.items() if n and re.search(r"\b" + re.escape(n) + r"\b", text)]


def delta(d):
    return d if isinstance(d, int) else (d.get("max", 0) if isinstance(d, dict) else 0)


lines = ["# Event lead organizations: what needs a look (generated by tools/audit_event_leads.py)", ""]
unfilled, over, only_in_choices, passive_many, none_at_all, set_not_named = [], [], [], [], [], []
for e in events:
    eid = e["event_id"]
    own = (e["title"] or "") + " " + (e["flavor"] or "")
    in_own = named(own)
    leads = e.get("lead_organizations") or []
    choice_text = " ".join((c.get("choice_text") or "") + " " + (c.get("result_text") or "") for c in by[eid])
    in_choices = [i for i in named(choice_text) if i not in in_own]
    positive = {r["target"] for c in by[eid] for r in (c.get("rewards") or []) if delta(r["delta"]) > 0}
    touched = {r["target"] for c in by[eid] for r in (c.get("rewards") or [])}
    if len(in_own) > 2:
        over.append((eid, in_own))
    if in_own and not leads:
        unfilled.append((eid, in_own))
    for lead in leads:
        if lead not in in_own:
            set_not_named.append((eid, lead))
    if not in_own and in_choices:
        only_in_choices.append((eid, in_choices))
    if len(positive) > 2:
        passive_many.append((eid, len(positive)))
    if not in_own and not touched and not in_choices:
        none_at_all.append(eid)


def name(i):
    return f"{i} {boosters.get(i, '?')}"


def section(title, items, fmt):
    lines.append(f"## {title} ({len(items)})")
    lines.append("")
    if not items:
        lines.append("None.")
    for it in items:
        lines.append("- " + fmt(it))
    lines.append("")


section("Event names more than two organizations in its own text (cannot all be leads; pick two)", over,
        lambda x: f"{x[0]}: " + ", ".join(name(i) for i in x[1]))
section("Names an organization in its own text but has no lead set", unfilled, lambda x: f"{x[0]}: " + ", ".join(name(i) for i in x[1]))
section("A lead is not named in the event's own title or flavor (check the wording or the lead)", set_not_named, lambda x: f"{x[0]}: {name(x[1])}")
section("No organization named in the event's own text, but a choice or result text names one (candidates for you to decide)",
        only_in_choices, lambda x: f"{x[0]}: " + ", ".join(name(i) for i in x[1]))
section("Choices give a passive plus to three or more organizations (not leads; listed for information)", passive_many,
        lambda x: f"{x[0]}: {x[1]} organizations")
section("No organization at all (no name, no reward)", none_at_all, lambda x: x)
text = "\n".join(lines) + "\n"
out = sys.argv[1] if len(sys.argv) > 1 else None
if out:
    open(out, "w").write(text)
    print(f"wrote {out}")
else:
    print(text)
