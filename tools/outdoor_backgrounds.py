#!/usr/bin/env python3
"""Plan the outside / constituency background pictures (2026-10-28).

Usage:  python3 tools/outdoor_backgrounds.py            # report to the screen
        python3 tools/outdoor_backgrounds.py --write    # also write design/OUTDOOR_BACKGROUNDS.md

The scenes (OUT_FESTIVAL, OUT_HARBOR, ...) are listed in data/art.json under
"outdoor_scenes", each with a label, keywords, a place and a mood. For each one
this shows:
  - whether assets/backgrounds/OUT_xxx.png (or numbered OUT_xxx_1.png ...) is drawn yet (until it is, the Town
    Hall picture shows in its place),
  - who uses it now (Events whose Image names it, Stages whose Background ID does),
  - how much existing content mentions its keywords (stage names, event titles
    and text, hosted-tour options, level names), as evidence for which scenes
    are worth drawing first,
  - a ready-to-paste art prompt in the house format (design/ART_PROMPT_TEMPLATE.md).
To use a scene for a stage, put OUT_xxx in its Background ID cell (Stages tab);
for an event, in its Image cell (Events tab). An Image cell may list several
pictures separated by semicolons (OUT_HARBOR_1; OUT_HARBOR_2); one is picked at random each time. Reads data/*.json only.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "data"
STYLE = ("STYLE: {HOUSE_STYLE}\nCANON GUARD: fictional nation Yezo; no real people or "
         "logos; no readable text anywhere.")


def load(name):
    with open(D / f"{name}.json", encoding="utf-8") as f:
        return json.load(f)


def main():
    art = load("art")
    scenes = art.get("outdoor_scenes", {})
    folder = ROOT / art["folders"]["background"].replace("res://", "")
    fallback = art.get("outdoor_background_fallback", "")
    stages, events = load("stages"), load("events")
    sources = [
        ("stage", [(s["stage_id"], s.get("name_en", "")) for s in stages]),
        ("event", [(e["event_id"], f"{e.get('title','')} {e.get('flavor','')}") for e in events]),
        ("tour option", [(o["option_id"], f"{o.get('choice_text','')} {o.get('flavor','')}") for o in load("event_options")]),
        ("level", [(l["level_id"], l.get("description", "")) for l in load("levels")]),
    ]
    out = ["# Outside backgrounds (generated by tools/outdoor_backgrounds.py)", "",
           f"Until a scene is drawn, the {fallback or 'fallback'} picture shows in its place.", "",
           "| Scene | Drawn | Used by (now) | Content mentions |", "|---|---|---|---|"]
    prompts = []
    for sid, sc in scenes.items():
        drawn = (folder / f"{sid}.png").exists() or bool(list(folder.glob(f"{sid}_*.png")))
        users = [e["event_id"] for e in events
                 if any(i.strip() == sid or i.strip().startswith(sid + "_")
                       for i in str(e.get("image") or "").replace("|", ";").split(";"))] + \
                [s["stage_id"] for s in stages if s.get("background_id") == sid]
        hits = 0
        for _kind, items in sources:
            for _ident, text in items:
                low = str(text).lower()
                if any(k in low for k in sc["keywords"]):
                    hits += 1
        out.append(f"| {sid} {sc['label']} | {'yes' if drawn else 'no'} | {', '.join(users) or '-'} | {hits} |")
        prompts.append(
            f"## {sid}{'_1' if sc.get('variants') else ''}.png  ({sc['label']})\n{STYLE}\n"
            f"Empty outdoor scene for constituency events: {sc['place']}. Mood: {sc['mood']}.\n"
            "Canvas 1080 x 2340 portrait, no people, calmer and darker lower third, "
            "open upper-middle for two characters in the bottom corners.\n")
        # A scene may list term pictures under "variants" (2026-10-30): each
        # is its own file with its own place and mood.
        for vid, variant in sc.get("variants", {}).items():
            prompts.append(
                f"## {vid}.png  ({sc['label']}, variant)\n{STYLE}\n"
                f"Empty outdoor scene for constituency events: {variant['place']}. Mood: {variant['mood']}.\n"
                "Canvas 1080 x 2340 portrait, no people, calmer and darker lower third, "
                "open upper-middle for two characters in the bottom corners.\n")
    text = "\n".join(out) + "\n\n" + "\n".join(prompts)
    print(text)
    if "--write" in sys.argv:
        (ROOT / "design" / "OUTDOOR_BACKGROUNDS.md").write_text(text, encoding="utf-8")
        print("wrote design/OUTDOOR_BACKGROUNDS.md")


if __name__ == "__main__":
    main()
