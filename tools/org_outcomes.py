"""Do some organizations come out worse than others in events, visitors and
visitor questions? Read-only; reads data/*.json and prints markdown.

Outcome = the signed standing change an effect gives an organization:
  event choices: `rewards` (immediate), `promise_kept` (+), `promise_broken` (-)
  visitors: `reward` (+) and `penalty` (-)
  visitor questions: the effects of each of the four answers
A delta that is a range (min/max) counts as its midpoint.

Usage: python3 tools/org_outcomes.py > design/review/ORG_OUTCOMES.md
"""
import json, math, collections, statistics as st
D = 'data/'
def load(f): return json.load(open(D + f + '.json'))
boosters = load('boosters'); names = {b['booster_id']: b['name_en'] for b in boosters}
tier = {b['booster_id']: b['tier'] for b in boosters}
IDS = sorted(names)
def val(d):
    if isinstance(d, dict): return (d['min'] + d['max']) / 2.0
    return float(d)
def entries(v):
    out = []
    if isinstance(v, list):
        for e in v:
            if isinstance(e, dict) and e.get('target') in names and e.get('delta') is not None:
                out.append((e['target'], val(e['delta'])))
    return out

class Tally:
    def __init__(self): self.pos = 0; self.neg = 0; self.pos_sum = 0.0; self.neg_sum = 0.0
    def add(self, d):
        if d > 0: self.pos += 1; self.pos_sum += d
        elif d < 0: self.neg += 1; self.neg_sum += -d
    @property
    def n(self): return self.pos + self.neg
    @property
    def neg_share(self): return self.neg / self.n if self.n else float('nan')
    @property
    def net(self): return self.pos_sum - self.neg_sum

def build(kind):
    T = {o: Tally() for o in IDS}
    if kind == 'events':
        for c in load('event_choices'):
            for k in ('rewards', 'promise_kept', 'promise_broken'):
                for o, d in entries(c.get(k)): T[o].add(d)
    elif kind == 'events_immediate':
        for c in load('event_choices'):
            for o, d in entries(c.get('rewards')): T[o].add(d)
    elif kind == 'visitors':
        for v in load('visitors'):
            for k in ('reward', 'penalty'):
                for o, d in entries(v.get(k)): T[o].add(d)
    elif kind == 'questions':
        for q in load('visitor_questions'):
            for k in ('effects_a', 'effects_b', 'effects_c', 'effects_d'):
                for o, d in entries(q.get(k)): T[o].add(d)
    return T

def table(T, title, min_n):
    tot = sum(t.n for t in T.values()); neg = sum(t.neg for t in T.values())
    p = neg / tot
    print('\n## %s\n' % title)
    print('Overall: %d outcomes, **%.0f%% negative** (%d). Organizations with fewer than %d outcomes are shown but not flagged.\n' % (tot, 100 * p, neg, min_n))
    print('| Org | Name | Tier | Positive | Negative | Negative share | Standing gained | Standing lost | Net | z vs overall | Flag |')
    print('|---|---|---|---|---|---|---|---|---|---|---|')
    rows = []
    for o in IDS:
        t = T[o]
        if t.n == 0: continue
        z = (t.neg - p * t.n) / math.sqrt(t.n * p * (1 - p)) if t.n else 0
        flag = ''
        if t.n >= min_n:
            flag = 'MORE negative' if z >= 2 else ('LESS negative' if z <= -2 else '')
        rows.append((z, o, t, flag))
    rows.sort(key=lambda r: -r[0])
    for z, o, t, flag in rows:
        print('| %s | %s | %s | %d | %d | %.0f%% | +%.0f | -%.0f | %+.0f | %+.1f | %s |' % (o, names[o], tier[o], t.pos, t.neg, 100 * t.neg_share, t.pos_sum, t.neg_sum, t.net, z, flag))
    return rows

print('# Positive and negative outcomes by organization\n')
print('Generated by `tools/org_outcomes.py`. z compares an organization\'s negative share with the overall rate (|z| of 2 or more is a real difference, not noise, for organizations with enough outcomes).')
ev = build('events'); table(ev, 'Event choices (immediate rewards plus promise kept and broken)', 8)
evi = build('events_immediate'); table(evi, 'Event choices, immediate rewards only', 8)
table(build('visitors'), 'Visitors (reward and penalty)', 8)
table(build('questions'), 'Visitor questions (all four answers)', 15)
