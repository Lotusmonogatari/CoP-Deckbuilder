"""Two offices, slice 7: what travel takes of the week, re-simulated on today's data.

Replays the strategy bot's logged runs (design/bench/pc_difficulty.jsonl: 4 protagonists x 3 Campaign Pressures x
12 runs, 30 weeks each) through the offices as built: today's Location, Travel Trips and Balance hours.

What is new compared with the audit's a6_hours.py (design/review/p11_two_offices_audit_2026-11-19):
  * the hours are the settled ones after the PC01/PC04 swap (PC01 7 h by train, 2 by plane; PC04 6 h by train, 4 by car);
  * a mixed level now charges its Travel Trips (2 for 21 Capitol levels, 1 for LV12/LV61/LV62) on top of its hours;
  * an odd number of trips moves the player to the other office (LV12/61/62 end at the Capitol).
What it still cannot model: the bot would pick different levels if only one office's list were shown, the logs predate
staff wages and tasks (so level hours per week are older numbers), and the eight new levels were never in the logs.
Treat every figure as an order of magnitude.

Usage: python3 tools/two_offices_hours.py <repo root> <output folder>   (the report: design/review/two_offices_hours_2026-11-20/)
"""
import collections
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
OUT = Path(sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)

TRAIN = {"PC01": 7, "PC02": 1, "PC03": 1, "PC04": 6}
FAST = {"PC01": 2, "PC02": 1, "PC03": 1, "PC04": 4}
FAST_NAME = {"PC01": "plane", "PC02": "car", "PC03": "car", "PC04": "car"}
NAMES = {"PC01": "PC01 Kenshin Sako (Aomori, Noheji)", "PC02": "PC02 Haru Yashi (Tomakomai, Akenoshinmachi)",
         "PC03": "PC03 Arata Ran (Sapporo, Teine Ward)", "PC04": "PC04 Jyurou Nishihara (Wakkanai, Daikoki)"}
RATING = {"PC01": "Easy", "PC02": "Normal", "PC03": "Hard", "PC04": "Very Hard"}
WEEK_HOURS = 40

levels = {r["level_id"]: r for r in json.load(open(ROOT / "data" / "levels.json", encoding="utf-8"))}
runs = [json.loads(line) for line in open(ROOT / "design" / "bench" / "pc_difficulty.jsonl", encoding="utf-8")]


def where(level_id):
    row = levels.get(level_id, {})
    loc = row.get("location") or "Either"
    return loc, int(row.get("travel_trips") or 0)


def other(office):
    return "District" if office == "Capitol" else "Capitol"


def simulate(by_week, hours_per_trip, batched):
    """Returns per-week lists: [(hours spent travelling, trips)] for one run, for the chosen order."""
    current = "Capitol"
    result = []
    for week in sorted(by_week):
        plays = [(lv, *where(lv)) for lv in by_week[week]]
        if batched:
            # Everything at the office the player is at first, then at most one crossing; mixed levels are played
            # at their start office, charging their own trips.
            plays.sort(key=lambda p: 0 if p[1] in (current, "Either") else 1)
        week_trips = 0
        week_mixed_trips = 0
        for lv, loc, trips in plays:
            if loc not in ("Either", current):
                week_trips += 1
                current = loc
            if trips:
                week_mixed_trips += trips
                if trips % 2:
                    current = other(current)
        result.append((week_trips, week_mixed_trips))
    return result


def main():
    stats = collections.defaultdict(list)
    level_hours = collections.defaultdict(list)
    mixed_share = collections.defaultdict(list)
    for run in runs:
        pc = run["protagonist"]
        by_week = collections.defaultdict(list)
        hours_in_week = collections.defaultdict(int)
        mixed_plays = 0
        for play in run["levels"]:
            by_week[play["week"]].append(play["level"])
            hours_in_week[play["week"]] += play["hours"]
            if where(play["level"])[1]:
                mixed_plays += 1
        weeks = max(run["weeks"], 1)
        level_hours[pc].append(sum(hours_in_week.values()) / weeks)
        mixed_share[pc].append(mixed_plays / max(len(run["levels"]), 1))
        for mode, per in (("rail pass", TRAIN), ("fast", FAST)):
            for order in ("as played", "batched"):
                weekly = simulate(by_week, per[pc], order == "batched")
                trips = sum(a for a, _ in weekly)
                mixed = sum(b for _, b in weekly)
                travel_hours = (trips + mixed) * per[pc]
                worst = max(((a + b) * per[pc] for a, b in weekly), default=0)
                heavy = sum(1 for a, b in weekly if (a + b) * per[pc] >= 12)
                stats[(pc, mode, order)].append({
                    "swipe_trips": trips / weeks, "mixed_trips": mixed / weeks,
                    "hours": travel_hours / weeks, "worst": worst, "heavy_weeks": heavy / weeks,
                    "pressure": run["difficulty"]})
    rows = []
    out = ["# Hours re-simulation with travel (slice 7)", "", "Generated by `tools/two_offices_hours.py`. Figures are means over the 36 runs per protagonist.", ""]
    out += ["## Travel per week, rail pass (free) and the fast mode (a ticket each trip)", "",
            "| Protagonist | Rating | Mode | Order | Swipe trips/wk | Mixed-level trips/wk | Travel h/wk | Share of 40 h | Worst week (h) | Weeks with 12+ h |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for pc in sorted(TRAIN):
        for mode in ("rail pass", "fast"):
            for order in ("as played", "batched"):
                rs = stats[(pc, mode, order)]
                m = lambda k: statistics.mean(r[k] for r in rs)
                label = mode if mode == "rail pass" else FAST_NAME[pc]
                summary[(pc, mode, order)] = (m("hours"), m("swipe_trips"), m("mixed_trips"))
                out.append("| %s | %s | %s | %s | %.2f | %.2f | %.1f | %.0f%% | %d | %.0f%% |" % (
                    NAMES[pc], RATING[pc], label, order, m("swipe_trips"), m("mixed_trips"), m("hours"), 100 * m("hours") / WEEK_HOURS,
                    max(r["worst"] for r in rs), 100 * m("heavy_weeks")))
                rows.append([pc, label, order, "%.3f" % m("swipe_trips"), "%.3f" % m("mixed_trips"), "%.2f" % m("hours"), "%.3f" % m("heavy_weeks")])
    out += ["", "## What the hours cost in levels (the number that matters for difficulty)", "",
            "A level takes about the logged mean; the table converts the weekly travel into levels not played, batched, on the rail pass.", "",
            "| Protagonist | Rating | Logged level hours/wk | Mean hours per level (logged) | Travel h/wk (batched, pass) | Levels given up per week | Mixed levels in the bot's plays |",
            "|---|---|---|---|---|---|---|"]
    for pc in sorted(TRAIN):
        total = 0
        count = 0
        for run in runs:
            if run["protagonist"] == pc:
                total += sum(p["hours"] for p in run["levels"])
                count += len(run["levels"])
        mean_level = total / count
        hours = summary[(pc, "rail pass", "batched")][0]
        out.append("| %s | %s | %.1f | %.1f | %.1f | %.2f | %.0f%% |" % (NAMES[pc], RATING[pc], statistics.mean(level_hours[pc]), mean_level, hours, hours / mean_level,
                                                                     100 * statistics.mean(mixed_share[pc])))
    out += ["", "## By Campaign Pressure (rail pass, batched, travel hours per week)", "",
            "| Protagonist | Relaxed | Standard | Harder |", "|---|---|---|---|"]
    for pc in sorted(TRAIN):
        cells = []
        for pressure in ("relaxed", "standard", "harder"):
            vals = [r["hours"] for r in stats[(pc, "rail pass", "batched")] if r["pressure"] == pressure]
            cells.append("%.1f" % statistics.mean(vals) if vals else "n/a")
        out.append("| %s | %s |" % (NAMES[pc], " | ".join(cells)))
    # What a ticket costs a week (fast mode, batched): trips a week x the ticket price (Shop rows SH42 to SH44).
    shop = {r["item_id"]: int(r.get("cost_yen") or 0) for r in json.load(open(ROOT / "data" / "shop.json", encoding="utf-8"))}
    price = {"PC01": shop["SH44"], "PC02": shop["SH43"], "PC03": shop["SH43"], "PC04": shop["SH43"]}
    out += ["", "## What the fast mode costs in Funds (batched: every trip by ticket)", "",
            "| Protagonist | Ticket | Price | Trips/wk | Funds/wk | Hours saved/wk against the pass |", "|---|---|---|---|---|---|"]
    for pc in sorted(TRAIN):
        _, swipe, mixed_trips = summary[(pc, "fast", "batched")]
        saved = summary[(pc, "rail pass", "batched")][0] - summary[(pc, "fast", "batched")][0]
        out.append("| %s | %s | %s円 | %.2f | %s円 | %.1f |" % (NAMES[pc], FAST_NAME[pc], format(price[pc], ","), swipe + mixed_trips, format(int((swipe + mixed_trips) * price[pc]), ","), saved))
    out += ["", "## What a mixed level costs (logged median hours, plus its trips)", "",
            "| Protagonist | Mixed levels | Median level hours | Median total on the pass | Median total fast | Over 40 h on the pass | Over 40 h fast |", "|---|---|---|---|---|---|---|"]
    played = collections.defaultdict(list)
    for run in runs:
        for play in run["levels"]:
            played[play["level"]].append(play["hours"])
    mixed = {lid: (statistics.median(played[lid]), int(levels[lid].get("travel_trips") or 0)) for lid in levels if int(levels[lid].get("travel_trips") or 0) and lid in played}
    for pc in sorted(TRAIN):
        base = [h for h, _ in mixed.values()]
        on_pass = [h + t * TRAIN[pc] for h, t in mixed.values()]
        fast = [h + t * FAST[pc] for h, t in mixed.values()]
        out.append("| %s | %d | %.1f | %.1f | %.1f | %d | %d |" % (NAMES[pc], len(mixed), statistics.median(base), statistics.median(on_pass), statistics.median(fast),
                                                              sum(1 for x in on_pass if x > WEEK_HOURS), sum(1 for x in fast if x > WEEK_HOURS)))
    (OUT / "hours_resim.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (OUT / "hours_resim_numbers.csv").write_text(
        "protagonist,mode,order,swipe_trips_per_week,mixed_trips_per_week,travel_hours_per_week,share_of_weeks_with_12h_or_more\n" +
        "\n".join(",".join(r) for r in rows) + "\n", encoding="utf-8")
    print("\n".join(out))


main()
