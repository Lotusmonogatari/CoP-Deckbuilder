#!/usr/bin/env python3
"""Pulls every gameplay number into tables (read-only). Run: python3 audit/gameplay/tuning_extract.py"""
import json, glob, re, collections, statistics as st
ROOT = "/home/user/CoP-Deckbuilder/"
J = lambda f: json.load(open(ROOT + "data/%s.json" % f))
bal = J("balance")
src = {f: open(f).read() for f in glob.glob(ROOT + "scripts/**/*.gd", recursive=True)}
def where(key):
    out = []
    for f, t in src.items():
        if '"%s"' % key in t: out.append(f.replace(ROOT, ""))
    return out
groups = collections.defaultdict(list)
for k, v in bal.items():
    pre = k.split("_")[0]
    groups[pre].append((k, v))
lines = ["# Balance tab, every row (generated by tuning_extract.py)\n", "| Key | Value | Read in |", "|---|---|---|"]
for k, v in bal.items():
    w = where(k)
    lines.append("| `%s` | %s | %s |" % (k, json.dumps(v) if not isinstance(v, (int, float)) else v, ", ".join(x.split("/")[-1] for x in w[:3]) or "(built key / unread)"))
open(ROOT + "audit/gameplay/tuning_balance.md", "w").write("\n".join(lines) + "\n")
print("balance rows", len(bal), "prefix groups", len(groups))
print({g: len(v) for g, v in sorted(groups.items(), key=lambda x: -len(x[1]))[:25]})
# stages
S = J("stages"); S = S if isinstance(S, list) else list(S.values())
def col(name, mode=None):
    v = [s.get(name) for s in S if (mode is None or s.get("mode") == mode) and isinstance(s.get(name), (int, float))]
    return v
for mode in ("Combat", "Non-combat", "Vote", "Visit", "Trade"):
    ss = [s for s in S if s["mode"] == mode]
    print(mode, len(ss))
for c in ("energy_per_turn", "hand_size", "gaffe_limit", "turn_limit", "bar_max", "win_threshold", "win_pct", "player_start", "opp_start", "time_units", "win_delta_xp", "win_delta_yen", "win_delta_jiban", "win_delta_reputation", "win_delta_party_support", "loss_delta_xp", "loss_delta_yen", "loss_delta_jiban", "loss_delta_reputation", "loss_delta_party_support"):
    v = col(c, "Combat")
    if v: print("%-26s n=%d min=%s med=%s mean=%.1f max=%s" % (c, len(v), min(v), st.median(v), st.mean(v), max(v)))
print(collections.Counter(s.get("bar_model") for s in S if s["mode"] == "Combat"))
print(collections.Counter(s.get("energy_mode") for s in S if s["mode"] == "Combat"))
